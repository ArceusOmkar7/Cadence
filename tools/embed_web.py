"""Embed web/viewer.html into include/viewer_page.h as a PROGMEM string, before each build.

The page is edited and previewed as a normal HTML file (open it with ?demo for simulated data).
The header is rewritten only when the content changes, so it never forces a needless rebuild.
"""
import os

Import("env")  # noqa: F821  (provided by PlatformIO's SCons)

project = env.subst("$PROJECT_DIR")
source = os.path.join(project, "web", "viewer.html")
target = os.path.join(project, "include", "viewer_page.h")
DELIMITER = "GLOVEVIEW"

with open(source, encoding="utf-8") as f:
    html = f.read()
if ")" + DELIMITER + '"' in html:
    raise SystemExit("web/viewer.html contains the raw-string terminator " + DELIMITER)

header = (
    "// Generated by tools/embed_web.py from web/viewer.html. Do not edit.\n"
    "#pragma once\n"
    "#include <pgmspace.h>\n"
    'const char VIEWER_PAGE[] PROGMEM = R"' + DELIMITER + "(" + html + ")" + DELIMITER + '";\n'
)

current = None
if os.path.exists(target):
    with open(target, encoding="utf-8", newline="") as f:
        current = f.read()
if current != header:
    with open(target, "w", encoding="utf-8", newline="") as f:
        f.write(header)
    print("embed_web: wrote include/viewer_page.h (%d bytes of HTML)" % len(html.encode("utf-8")))
